import { test, expect } from '@playwright/test';
import { zipSync, strToU8 } from 'fflate';
import fs from 'node:fs';
const manifest={version:1,title:'Synthetic audit',nodes:[{id:'s1',type:'screen',position:{x:70,y:100},data:{title:'Home',image:'assets/a.png'}},{id:'s2',type:'screen',position:{x:400,y:100},data:{title:'Next',image:'assets/a.png'}},{id:'n1',type:'note',position:{x:70,y:520},data:{title:'Audit',text:'Baseline only'}}],edges:[{id:'e1',source:'s1',target:'s2',label:'Continue'}]};
test('ARCH-01..04 archive, reload, independent board and clean-profile roundtrip',async({page,browser})=>{
 await page.goto('/?board=existing-test');
 await page.getByRole('button',{name:'Добавить заметку',exact:true}).click();
 await page.getByLabel('Текст заметки').fill('Keep this board');
 await expect(page.getByRole('status').filter({hasText:'Сохранено'})).toBeVisible();
 const payload=Buffer.from(zipSync({'board.json':strToU8(JSON.stringify(manifest)),'assets/a.png':fs.readFileSync('tests/fixtures/Вход.png')}));
 await page.getByLabel('Импорт архива').setInputFiles({name:'audit.zip',mimeType:'application/zip',buffer:payload});
 await expect(page.getByTestId('screen-node')).toHaveCount(2);
 await expect(page.getByText('Continue',{exact:true})).toBeVisible();
 const imported=page.url(); expect(imported).not.toContain('existing-test');
 await page.getByLabel('Текст заметки').fill('Updated comment');
 await page.getByLabel('Подпись перехода').fill('Open details');
 await expect(page.getByRole('status').filter({hasText:'Сохранено'})).toBeVisible();
 await page.reload();
 await expect(page.getByLabel('Текст заметки')).toHaveValue('Updated comment');
 await expect(page.getByText('Open details',{exact:true})).toBeVisible();
 await page.getByLabel('Импорт архива').setInputFiles({name:'bad.zip',mimeType:'application/zip',buffer:Buffer.from('bad')});
 await expect(page.getByRole('alert')).toBeVisible();
 expect(page.url()).toBe(imported);
 await expect(page.getByTestId('screen-node')).toHaveCount(2);
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Экспорт архива'}).click();
 const download=await downloadPromise; const archive=await download.path();
 const clean=await browser.newContext(); const other=await clean.newPage();
 await other.goto('/'); await other.getByLabel('Импорт архива').setInputFiles(archive!);
 await expect(other.getByTestId('screen-node')).toHaveCount(2);
 await expect(other.getByLabel('Текст заметки')).toHaveValue('Updated comment');
 await expect(other.getByText('Open details',{exact:true})).toBeVisible();
 await other.reload(); await expect(other.getByTestId('screen-node')).toHaveCount(2); await clean.close();
 await page.goto('/?board=existing-test'); await expect(page.getByLabel('Текст заметки')).toHaveValue('Keep this board');
});
